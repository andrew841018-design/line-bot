def push(chunk: str) -> str:
    """Next.js 的寫法：JSON 字串，< > & 變成 \\u003c \\u003e \\u0026（中文不跳脫）。"""
    quoted = json.dumps(chunk, ensure_ascii=False)
    quoted = quoted.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
    return f"<script>self.__next_f.push([1,{quoted}])</script>"


def page_of(chunks) -> str:
    return HEAD + "".join(push(chunk) for chunk in chunks) + "</body></html>"


def flight_of(data: dict) -> str:
    return "".join((*ROWS_BEFORE, data_row(data), *ROWS_AFTER))


def make_page(data: dict | None = None, *, split: int | None = None) -> str:
    """預設照保存的回應：每一行各一個 push。split＝合成：整份 flight 文字每 split 個字元切一個 push。"""
    data = make_data() if data is None else data
    if split is None:
        return page_of((*ROWS_BEFORE, data_row(data), *ROWS_AFTER))
    text = flight_of(data)
    return page_of([text[i:i + split] for i in range(0, len(text), split)])


def make_bytes(*args, **kwargs) -> bytes:
    return make_page(*args, **kwargs).encode("utf-8")


